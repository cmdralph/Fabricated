package io.github.cmdralph.fabricated.core.translate;

import java.util.List;
import java.util.stream.Collectors;

import net.fabricmc.loader.api.metadata.Person;

/**
 * Generates the {@code META-INF/neoforge.mods.toml} that presents a translated Fabric mod to NeoForge.
 *
 * <p>Dependencies are emitted only for load ordering ({@code type="optional"}, {@code ordering="AFTER"}):
 * Fabricated resolves required dependencies itself so that one unsatisfied Fabric mod cannot abort the
 * whole game (see {@code DependencyResolver}).
 */
public final class ModsTomlWriter {
	/** Name of Fabricated's NeoForge language loader. */
	public static final String LANGUAGE_LOADER = "fabricated";

	/** Everything needed to describe one translated mod. */
	public record Spec(
			String neoForgeId,
			String version,
			String displayName,
			String description,
			List<Person> authors,
			List<Person> contributors,
			List<String> license,
			String homepage,
			String issues,
			String logoFile,
			List<MixinConfigSpec> mixins,
			boolean hasAccessTransformer,
			List<String> loadAfter) {
	}

	/** One {@code [[mixins]]} block. */
	public record MixinConfigSpec(String config, String behaviorVersion) {
	}

	private ModsTomlWriter() {
	}

	public static String write(Spec spec, String loaderVersionRange) {
		StringBuilder sb = new StringBuilder();
		sb.append("# Generated by Fabricated from fabric.mod.json. Do not edit.\n");
		kv(sb, "modLoader", LANGUAGE_LOADER);
		kv(sb, "loaderVersion", loaderVersionRange);
		String license = spec.license().isEmpty() ? "All Rights Reserved" : String.join(", ", spec.license());
		kv(sb, "license", license);
		if (spec.issues() != null) kv(sb, "issueTrackerURL", spec.issues());
		sb.append('\n');

		sb.append("[[mods]]\n");
		kv(sb, "modId", spec.neoForgeId());
		kv(sb, "version", spec.version());
		kv(sb, "displayName", spec.displayName());
		kv(sb, "description", spec.description());
		if (!spec.authors().isEmpty()) kv(sb, "authors", names(spec.authors()));
		if (!spec.contributors().isEmpty()) kv(sb, "credits", names(spec.contributors()));
		if (spec.homepage() != null) kv(sb, "displayURL", spec.homepage());
		if (spec.logoFile() != null) kv(sb, "logoFile", spec.logoFile());
		sb.append('\n');

		for (MixinConfigSpec mixin : spec.mixins()) {
			sb.append("[[mixins]]\n");
			kv(sb, "config", mixin.config());
			kv(sb, "behaviorVersion", mixin.behaviorVersion());
			sb.append('\n');
		}

		if (spec.hasAccessTransformer()) {
			sb.append("[[accessTransformers]]\n");
			kv(sb, "file", "META-INF/accesstransformer.cfg");
			sb.append('\n');
		}

		for (String after : spec.loadAfter()) {
			sb.append("[[dependencies.").append(spec.neoForgeId()).append("]]\n");
			kv(sb, "modId", after);
			kv(sb, "type", "optional");
			kv(sb, "ordering", "AFTER");
			kv(sb, "side", "BOTH");
			sb.append('\n');
		}
		return sb.toString();
	}

	private static String names(List<Person> people) {
		return people.stream().map(Person::getName).collect(Collectors.joining(", "));
	}

	private static void kv(StringBuilder sb, String key, String value) {
		sb.append(key).append('=');
		quote(sb, value);
		sb.append('\n');
	}

	/** Writes a TOML basic string with every special character escaped. */
	static void quote(StringBuilder sb, String value) {
		sb.append('"');
		for (int i = 0; i < value.length(); i++) {
			char c = value.charAt(i);
			switch (c) {
				case '"' -> sb.append("\\\"");
				case '\\' -> sb.append("\\\\");
				case '\n' -> sb.append("\\n");
				case '\r' -> sb.append("\\r");
				case '\t' -> sb.append("\\t");
				case '\b' -> sb.append("\\b");
				case '\f' -> sb.append("\\f");
				default -> {
					if (c < 0x20 || c == 0x7f) {
						sb.append(String.format("\\u%04X", (int) c));
					} else {
						sb.append(c);
					}
				}
			}
		}
		sb.append('"');
	}
}
