package io.github.cmdralph.fabricated.core.translate;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

import io.github.cmdralph.fabricated.core.metadata.ModIds;

import net.fabricmc.loader.api.metadata.Person;

/**
 * Generates the {@code META-INF/neoforge.mods.toml} that presents a translated Fabric mod to NeoForge.
 *
 * <p>Dependencies are emitted only for load ordering ({@code type="optional"}, {@code ordering="AFTER"}):
 * Fabricated resolves required dependencies itself so that one unsatisfied Fabric mod cannot abort the
 * whole game (see {@code DependencyResolver}).
 */
public final class ModsTomlWriter {
	public static final String PATH = "META-INF/neoforge.mods.toml";
	/** Name of Fabricated's NeoForge language loader. */
	public static final String LANGUAGE_LOADER = "fabricated";

	/**
	 * Everything needed to describe one translated mod. Property and option values are strings, numbers, booleans, and
	 * lists and maps of them.
	 *
	 * @param hasEnumExtensions whether the overlay has an enum extension file ({@link EnumExtensions}), which NeoForge's
	 *                      loader reads from the mod's {@code [[mods]]} entry
	 * @param modProperties its {@code [modproperties.<id>]}, which NeoForge mods read where Fabric mods read entrypoints
	 *                      or custom values
	 * @param options       keys written both at the file's top level and in the mod's {@code [[mods]]} entry, where
	 *                      NeoForge mods read per-mod settings (Lithium's and Sodium's option overrides); none may be one
	 *                      of NeoForge's own keys
	 */
	public record Spec(
			String neoForgeId,
			String version,
			String displayName,
			String description,
			List<Person> authors,
			List<Person> contributors,
			List<String> license,
			String homepage,
			String issues,
			String logoFile,
			List<MixinConfigSpec> mixins,
			boolean hasAccessTransformer,
			boolean hasEnumExtensions,
			List<String> loadAfter,
			Map<String, Object> modProperties,
			Map<String, Object> options) {
	}

	/** One {@code [[mixins]]} block. */
	public record MixinConfigSpec(String config, String behaviorVersion) {
	}

	private ModsTomlWriter() {
	}

	/**
	 * The version as NeoForge's loader takes it: one starting with a digit (FML's {@code ModInfo} refuses any other, and
	 * stops the launch). Fabric's needn't, as a nested library's {@code animated-gif-lib-1.7} didn't (run 381), so such a
	 * version gets {@code 0+} in front. Fabric mods still see their own version through Fabric's API.
	 */
	static String neoForgeVersion(String version) {
		return !version.isEmpty() && version.charAt(0) >= '0' && version.charAt(0) <= '9' ? version : "0+" + version;
	}

	public static String write(Spec spec) {
		StringBuilder sb = new StringBuilder();
		sb.append("# Generated by Fabricated from fabric.mod.json. Do not edit.\n");
		kv(sb, "modLoader", LANGUAGE_LOADER);
		kv(sb, "loaderVersion", "[0,)");
		String license = spec.license().isEmpty() ? "All Rights Reserved" : String.join(", ", spec.license());
		kv(sb, "license", license);
		if (spec.issues() != null) kv(sb, "issueTrackerURL", spec.issues());
		entries(sb, spec.options());
		sb.append('\n');

		sb.append("[[mods]]\n");
		kv(sb, "modId", spec.neoForgeId());
		kv(sb, "version", neoForgeVersion(spec.version()));
		kv(sb, "displayName", spec.displayName());
		kv(sb, "description", spec.description());
		if (!spec.authors().isEmpty()) kv(sb, "authors", names(spec.authors()));
		if (!spec.contributors().isEmpty()) kv(sb, "credits", names(spec.contributors()));
		if (spec.homepage() != null) kv(sb, "displayURL", spec.homepage());
		if (spec.logoFile() != null) kv(sb, "logoFile", spec.logoFile());
		if (spec.hasEnumExtensions()) kv(sb, "enumExtensions", EnumExtensions.PATH);
		entries(sb, spec.options());
		sb.append('\n');

		if (!spec.modProperties().isEmpty()) {
			sb.append("[modproperties.").append(spec.neoForgeId()).append("]\n");
			entries(sb, spec.modProperties());
			sb.append('\n');
		}

		for (MixinConfigSpec mixin : spec.mixins()) {
			sb.append("[[mixins]]\n");
			kv(sb, "config", mixin.config());
			kv(sb, "behaviorVersion", mixin.behaviorVersion());
			sb.append('\n');
		}

		if (spec.hasAccessTransformer()) {
			sb.append("[[accessTransformers]]\n");
			kv(sb, "file", ModTranslator.AT_PATH);
			sb.append('\n');
		}

		// After Fabricated's own mod, whose mixin config plugin creates the Fabric mods' language adapters before any
		// Fabric mod's mixin plugin loads (FML registers mixin configs in this order), as Fabric Loader does.
		List<String> after = new ArrayList<>(spec.loadAfter());
		if (!after.contains(ModIds.FABRICATED)) after.add(0, ModIds.FABRICATED);
		for (String id : after) {
			sb.append("[[dependencies.").append(spec.neoForgeId()).append("]]\n");
			kv(sb, "modId", id);
			kv(sb, "type", "optional");
			kv(sb, "ordering", "AFTER");
			kv(sb, "side", "BOTH");
			sb.append('\n');
		}
		return sb.toString();
	}

	private static String names(List<Person> people) {
		return people.stream().map(Person::getName).collect(Collectors.joining(", "));
	}

	private static void kv(StringBuilder sb, String key, String value) {
		sb.append(key).append('=');
		quote(sb, value);
		sb.append('\n');
	}

	/** One {@code "key"=value} line per entry. */
	private static void entries(StringBuilder sb, Map<String, Object> entries) {
		for (Map.Entry<String, Object> entry : entries.entrySet()) {
			quote(sb, entry.getKey());
			sb.append('=');
			value(sb, entry.getValue());
			sb.append('\n');
		}
	}

	/** A string, number, boolean, array ({@code List}) or inline table ({@code Map}). */
	private static void value(StringBuilder sb, Object value) {
		if (value instanceof Map<?, ?> table) {
			sb.append('{');
			String separator = "";
			for (Map.Entry<?, ?> entry : table.entrySet()) {
				sb.append(separator);
				quote(sb, String.valueOf(entry.getKey()));
				sb.append('=');
				value(sb, entry.getValue());
				separator = ", ";
			}
			sb.append('}');
		} else if (value instanceof List<?> list) {
			sb.append('[');
			String separator = "";
			for (Object element : list) {
				sb.append(separator);
				value(sb, element);
				separator = ", ";
			}
			sb.append(']');
		} else if (value instanceof Double || value instanceof Float) {
			// TOML spells the non-finite ones its own way (a JSON number too large for a double is infinite).
			double d = ((Number) value).doubleValue();
			sb.append(Double.isNaN(d) ? "nan" : d == Double.POSITIVE_INFINITY ? "inf" : d == Double.NEGATIVE_INFINITY ? "-inf" : value.toString());
		} else if (value instanceof Number || value instanceof Boolean) {
			sb.append(value);
		} else {
			quote(sb, String.valueOf(value));
		}
	}

	/** Writes a TOML basic string with every special character escaped. */
	static void quote(StringBuilder sb, String value) {
		sb.append('"');
		for (int i = 0; i < value.length(); i++) {
			char c = value.charAt(i);
			switch (c) {
				case '"' -> sb.append("\\\"");
				case '\\' -> sb.append("\\\\");
				case '\n' -> sb.append("\\n");
				case '\r' -> sb.append("\\r");
				case '\t' -> sb.append("\\t");
				case '\b' -> sb.append("\\b");
				case '\f' -> sb.append("\\f");
				default -> {
					if (c < 0x20 || c == 0x7f) {
						sb.append(String.format("\\u%04X", (int) c));
					} else {
						sb.append(c);
					}
				}
			}
		}
		sb.append('"');
	}
}
